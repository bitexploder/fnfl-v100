// [TAG_ROUND_TIMERS] (ticket 0089) the per-round timer registry behind LLAMA_ROUND_TIMERS (ggml-rtimer.h)

#include "ggml-rtimer.h"

#include <chrono>
#include <map>
#include <mutex>
#include <string>

namespace {
struct ggml_rt_acc { int64_t ns = 0; int64_t n = 0; };
struct ggml_rt_stat { double sum = 0; double sum2 = 0; int64_t n = 0; void add(double v) { sum += v; sum2 += v*v; n++; } };

struct ggml_rt_state {
    std::mutex mu;
    std::vector<const char *> names;
    std::vector<bool> global;
    std::vector<const void *> ctxs;
    int label = -1;
    std::map<std::pair<int,int>, ggml_rt_acc> cur, tot;
    ggml_rt_collect_fn collect = nullptr;
    // rounds since the last report; the first one (it carries the prompt) is dropped
    int64_t n_marks = 0, n_rounds = 0;
    std::chrono::steady_clock::time_point t_mark;
    // (ticket P4d) the GPU stamps per device (the collector puts the device in tag bits 24 and up); labels in span and
    // gap carry the device in bits 20 and up
    static constexpr int MAX_DEV = 16;
    ggml_rt_stat wall, gpu_round[MAX_DEV], gpu_busy[MAX_DEV], gpu_idle[MAX_DEV], n_graphs[MAX_DEV];
    std::map<int, ggml_rt_stat> span;                    // per label
    std::map<std::pair<int,int>, ggml_rt_stat> gap;      // per (previous label, label)
    uint64_t prev_end[MAX_DEV] = {}; int prev_label[MAX_DEV];
    bool open[MAX_DEV] = {}; uint64_t open_t[MAX_DEV] = {}; int open_label[MAX_DEV];
    int n_dev = 1;
    int64_t n_lost = 0; // (ticket P4h) ring wraps seen since the last report
    std::vector<uint64_t> bt; std::vector<uint32_t> btag;
    ggml_rt_state() { for (int d = 0; d < MAX_DEV; ++d) { prev_label[d] = -1; open_label[d] = -1; } }
};
ggml_rt_state & ggml_rt() { static ggml_rt_state s; return s; }

std::string ggml_rt_lname(int l) {
    if (l < 0) return "-";
    const int d = l >> 20; l &= (1 << 20) - 1;
    return (d > 0 ? "d" + std::to_string(d) + ":" : std::string()) + "c" + std::to_string(l / 64) + "/" + std::to_string(l % 64);
}
}

bool ggml_rt_on(void) {
    static const bool on = [] { const char * e = getenv("LLAMA_ROUND_TIMERS"); return e != nullptr && atoi(e) != 0; }();
    return on;
}

int ggml_rt_id(const char * name) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    for (size_t i = 0; i < s.names.size(); ++i) {
        if (strcmp(s.names[i], name) == 0) return (int) i;
    }
    s.names.push_back(name);
    s.global.push_back(strncmp(name, "srv.", 4) == 0 || strncmp(name, "spec.", 5) == 0 || strncmp(name, "smpl.", 5) == 0);
    return (int) s.names.size() - 1;
}

void ggml_rt_add(int id, int64_t ns) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    auto & a = s.cur[{id, s.global[id] ? -1 : s.label}];
    a.ns += ns; a.n++;
}

void ggml_rt_cnt(int id, int64_t n) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    s.cur[{id, s.global[id] ? -1 : s.label}].n += n;
}

void ggml_rt_label(const void * ctx, int n_tokens) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    size_t c = 0;
    while (c < s.ctxs.size() && s.ctxs[c] != ctx) c++;
    if (c == s.ctxs.size()) s.ctxs.push_back(ctx);
    s.label = (int) c * 64 + std::min(n_tokens, 63);
}

int ggml_rt_cur_label(void) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    return s.label;
}

void ggml_rt_set_collector(ggml_rt_collect_fn fn) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    s.collect = fn;
}

void ggml_rt_round(void) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    const auto now = std::chrono::steady_clock::now();
    const bool keep = s.n_marks > 0;
    s.n_marks++;
    // the GPU stamps of this round: start (bit 0 clear) and end (bit 0 set) of every graph, in stream order per device
    constexpr int MD = ggml_rt_state::MAX_DEV;
    double busy[MD] = {}; int ng[MD] = {}; uint64_t first_end_prev[MD]; bool lost[MD] = {};
    for (int d = 0; d < MD; ++d) first_end_prev[d] = s.prev_end[d];
    if (s.collect) {
        // (ticket P4h) room for a long prefill's stamps on every device (the collector shares it equally between devices)
        s.bt.resize(1 << 18); s.btag.resize(1 << 18);
        const int n = s.collect(s.bt.data(), s.btag.data(), (int) s.bt.size());
        for (int i = 0; i < n; ++i) {
            const int dv = std::min((int) (s.btag[i] >> 24), MD - 1); s.n_dev = std::max(s.n_dev, dv + 1);
            if ((s.btag[i] & 0xffffffu) == GGML_RT_TAG_LOST) {
                // (ticket P4h) the device's ring wrapped: no gap, span or round across the hole
                lost[dv] = true; s.open[dv] = false; s.prev_end[dv] = 0; s.n_lost++;
                continue;
            }
            const uint64_t t = s.bt[i]; const int l = (int) ((s.btag[i] & 0xffffffu) >> 1) | (dv << 20); const bool end = s.btag[i] & 1;
            if (!end) {
                if (keep && s.prev_end[dv] != 0) s.gap[{s.prev_label[dv], l}].add((double) (t - s.prev_end[dv]) * 1e-3);
                s.open[dv] = true; s.open_t[dv] = t; s.open_label[dv] = l;
            } else if (s.open[dv]) {
                const double d = (double) (t - s.open_t[dv]) * 1e-3;
                if (keep) { s.span[l].add(d); busy[dv] += d; ng[dv]++; }
                s.open[dv] = false; s.prev_end[dv] = t; s.prev_label[dv] = l;
            }
        }
    }
    if (keep) {
        s.n_rounds++;
        s.wall.add(std::chrono::duration<double, std::micro>(now - s.t_mark).count());
        for (int d = 0; d < s.n_dev; ++d) {
            if (!lost[d] && first_end_prev[d] != 0 && s.prev_end[d] > first_end_prev[d]) {
                const double r = (double) (s.prev_end[d] - first_end_prev[d]) * 1e-3;
                s.gpu_round[d].add(r); s.gpu_busy[d].add(busy[d]); s.gpu_idle[d].add(r - busy[d]); s.n_graphs[d].add(ng[d]);
            }
        }
        for (auto & [k, a] : s.cur) { auto & t = s.tot[k]; t.ns += a.ns; t.n += a.n; }
    }
    s.cur.clear();
    s.t_mark = now;
}

void ggml_rt_report(const char * label) {
    auto & s = ggml_rt();
    std::lock_guard<std::mutex> lock(s.mu);
    const double R = (double) std::max<int64_t>(s.n_rounds, 1);
    auto m = [](const ggml_rt_stat & x) { return x.n ? x.sum / x.n : 0.0; };
    fprintf(stderr, "round_timers %s: %lld rounds (the first dropped); host round %.1f us; GPU round %.1f us = busy %.1f + idle %.1f us over %.2f graphs (%lld rounds with stamps)\n",
            label, (long long) s.n_rounds, m(s.wall), m(s.gpu_round[0]), m(s.gpu_busy[0]), m(s.gpu_idle[0]), m(s.n_graphs[0]), (long long) s.gpu_round[0].n);
    for (int d = 1; d < s.n_dev; ++d) {
        fprintf(stderr, "round_timers %s: device %d: GPU round %.1f us = busy %.1f + idle %.1f us over %.2f graphs (%lld rounds with stamps)\n",
                label, d, m(s.gpu_round[d]), m(s.gpu_busy[d]), m(s.gpu_idle[d]), m(s.n_graphs[d]), (long long) s.gpu_round[d].n);
    }
    if (s.n_lost > 0) {
        fprintf(stderr, "round_timers %s: %lld stamp ring wraps (the rounds that lost stamps are not counted)\n", label, (long long) s.n_lost);
    }
    for (auto & [l, x] : s.span) {
        fprintf(stderr, "round_timers %s: span  %-6s %6.2f per round, mean %8.1f us\n", label, ggml_rt_lname(l).c_str(), x.n / R, m(x));
    }
    for (auto & [k, x] : s.gap) {
        fprintf(stderr, "round_timers %s: gap   %-6s -> %-6s %6.2f per round, mean %8.1f us, per round %8.1f us\n", label,
                ggml_rt_lname(k.first).c_str(), ggml_rt_lname(k.second).c_str(), x.n / R, m(x), x.sum / R);
    }
    for (auto & [k, a] : s.tot) {
        fprintf(stderr, "round_timers %s: phase %-28s %-6s %8.1f us per round, %7.2f per round%s\n", label, s.names[k.first],
                ggml_rt_lname(k.second).c_str(), a.ns * 1e-3 / R, a.n / R, a.ns ? "" : " (count)");
    }
    s.tot.clear(); s.cur.clear(); s.span.clear(); s.gap.clear();
    s.wall = ggml_rt_stat();
    for (int d = 0; d < ggml_rt_state::MAX_DEV; ++d) s.gpu_round[d] = s.gpu_busy[d] = s.gpu_idle[d] = s.n_graphs[d] = ggml_rt_stat();
    s.n_marks = 0; s.n_rounds = 0; s.n_lost = 0;
    fflush(stderr);
}
